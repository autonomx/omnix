def run_story_job(run: JobRun[Any]) -> JobResult:
    """Write a story or podcast script; a failure is retried (``story_job_failed``)."""
    job = run.job
    result = _render_job(job, run)
    return JobResult(
        output_refs=({
            "type": result["artifact_type"],
            "module": job.module,
            "title": result["title"],
            "content": result["content"],
            "provider_id": result.get("provider_id"),
            "model_id": result.get("model_id"),
            "resolved_model": result.get("resolved_model"),
            **({"script_quality": result["script_quality"]} if result.get("script_quality") else {}),
            # The project and the page or version the job wrote (ST-1.3).
            **(result["story_ref"] if result.get("story_ref") else {}),
        },),
        logs=({"level": "info", "message": result["log_message"], "content": result["content"]},),
    )


def _render_job(job: JobRecord, run: JobRun[Any] | None = None) -> dict[str, Any]:
    payload = job.input_payload or {}
    provider_id = _text(payload.get("provider_id"))
    model_id = _text(payload.get("model_id"))

    if job.type == "story.generate":
        return _render_story(job, payload, provider_id=provider_id, model_id=model_id, run=run)

    if job.type == "podcast.generate":
        title = _text(payload.get("title")) or "Untitled episode"
        brief = _require_text(payload.get("brief"), "Podcast brief is required")
        script = write_podcast_script(
            payload,
            title=title,
            brief=brief,
            complete=lambda prompt: _call_chat_provider(prompt, provider_id=provider_id, model_id=model_id),
            progress=_progress_reporter(run),
            cancelled=run.cancelled if run is not None else None,
        )
        return {
            "artifact_type": "podcast_script",
            "title": title,
            "content": script_json(script.lines),
            "log_message": "Podcast script generated by local provider",
            "provider_id": provider_id,
            "model_id": model_id,
            "resolved_model": script.model,
            "script_quality": script.quality,
        }

    raise RuntimeError(f"Unsupported story job type: {job.type}")


def _render_story(job: JobRecord, payload: dict[str, Any], *, provider_id: str | None,
                  model_id: str | None, run: JobRun[Any] | None = None) -> dict[str, Any]:
    """Write a page or a version of the job's project (ST-1.3), or several chapters one after another.

    A Generate of ``chapters`` writes that many pages into the same story: the first where the request says, each
    after it opening the next chapter from the story as the one before left it. Each chapter is stored under its own
    key (the job's id, then ``<job id>:<n>``), so a retried job keeps the chapters it wrote and writes the rest.
    """
    count = _chapter_count(payload)
    if count == 1:
        return _render_page(job.id, payload, provider_id=provider_id, model_id=model_id, run=run)
    written: list[dict[str, Any]] = []
    for index in range(count):
        _stop_if_cancelled(run)
        _report(run, index + 1, count, f"Writing chapter {index + 1} of {count}")
        step = payload if not written else {
            **payload, "action": "continue", "new_chapter": True, "project_id": written[0]["story_ref"]["project_id"],
            "title": None, "generate_title": False,
        }
        written.append(_render_page(job.id if not written else f"{job.id}:{index + 1}", step,
                                    provider_id=provider_id, model_id=model_id, run=run))
    first = written[0]
    return {
        **first,
        "content": "\n\n".join(result["content"] for result in written),
        "resolved_model": next((result["resolved_model"] for result in reversed(written) if result["resolved_model"]),
                               None),
        "story_ref": {**first["story_ref"], "page_ids": [result["story_ref"].get("page_id") for result in written]},
    }


def _chapter_count(payload: dict[str, Any]) -> int:
    """How many chapters a Generate writes: 1 to PLANNED_CHAPTERS_MAX for a writing draft or continue, else 1."""
    count = payload.get("chapters")
    if not isinstance(count, int) or isinstance(count, bool) or not 1 <= count <= PLANNED_CHAPTERS_MAX:
        return 1
    if (_text(payload.get("action")) or "draft") not in {"draft", "continue"} \
            or (_text(payload.get("interaction_mode")) or "writing") == "story" \
            or _text(payload.get("beat_id")) or payload.get("selection") is not None:
        return 1
    return count


def _render_page(job_id: str, payload: dict[str, Any], *, provider_id: str | None,
                 model_id: str | None, run: JobRun[Any] | None = None) -> dict[str, Any]:
    """Write a page or a version of the job's project (ST-1.3), one page per model call (ST-2.1).

    The project supplies the story so far and its bible. A retried job whose page or version is
    already stored under ``job_id`` returns it without calling the model again.
    """
    from app.persistence.database import default_database
    from app.runtime.tenant_context import current_tenant

    from . import service

    database, context = default_database(), current_tenant()
    requested_title = _text(payload.get("title"))
    premise = _require_text(payload.get("premise"), "Story premise is required")
    action = _text(payload.get("action")) or "draft"
    interaction_mode = _text(payload.get("interaction_mode")) or "writing"
    project = service.job_project(
        database, context, project_id=_text(payload.get("project_id")), job_id=job_id, premise=premise,
        mode="interactive" if interaction_mode == "story" else "writing",
        tone=_text(payload.get("tone")), writing_style=_text(payload.get("writing_style")),
    )
    project_id = project["project"]["id"]
    if project["written"] is not None:
        # A retry of a job that already wrote its page reports it before anything that depends on the story
        # as it now is (a beat removed since, a preset changed), which could fail a job whose page exists.
        written = service.written_by_job(database, context, project_id, job_id)
        return _story_result(written["title"] or requested_title or "Untitled story", written["content"],
                             written["ref"], provider_id=provider_id, model_id=model_id, resolved_model=None)
    style_notes = _preset_instructions(project)
    if action == "outline":
        return _plan_story(job_id, payload, project, premise=premise, title=requested_title, style_notes=style_notes,
                           provider_id=provider_id, model_id=model_id)
    planned = _planned_beat(project, payload, interaction_mode)
    if planned is not None:
        action = "continue" if project["page_count"] else "draft"
    # The chapter being written: a new story opens at chapter 1, otherwise the chapter the story ends in (or the
    # next one), never the one the writer happens to be viewing. A request's own chapter number is ignored.
    chapter = 1 if action == "draft" and not project["last_chapter"] else None
    new_chapter = action == "continue" and payload.get("new_chapter") is True and interaction_mode != "story"
    if new_chapter:
        chapter = project["last_chapter"] + 1
    elif chapter is None and action == "continue" and project["last_chapter"]:
        chapter = project["last_chapter"]
    if planned is not None:
        # A beat is written into its own chapter of the plan, which opens when the story hasn't reached it.
        chapter = int(planned[0]["chapter"])
        new_chapter = bool(project["last_chapter"]) and chapter > project["last_chapter"]

    cast = list(project["characters"])
    prompt_values = dict(
        premise=premise, action=action, interaction_mode=interaction_mode,
        title=requested_title or project["project"]["title"] or None,
        generate_title=bool(payload.get("generate_title")) or (
            requested_title is None and not project["project"]["title"]),
        user_response=_text(payload.get("user_response")), tone=_text(payload.get("tone")),
        writing_style=_text(payload.get("writing_style")), chapter=chapter, new_chapter=new_chapter,
        page_lines=_page_lines(payload.get("page_lines")), notes=project["notes"], style_notes=style_notes,
        beat=_beat_text(*planned) if planned is not None else None,
    )
    # The project's own pages are the story so far; a job queued before projects carried its text.
    stored = project["pages"]
    if interaction_mode == "story":
        # An interactive page is written from a summary and the last pages, never the whole run (ST-3.3).
        summary, story_text = interactive_context(stored)
        story_text = story_text or text_tail(_text(payload.get("source_text")) or "", RECENT_MAX_CHARS) or None
        prompt_values["summary"] = summary
    else:
        story_text = text_tail("\n\n".join(tagged_text(page["blocks"]) for page in stored)
                               or _text(payload.get("source_text")) or "", MANUSCRIPT_MAX_CHARS) or None
        if planned is not None:
            # A beat is drafted from the rolling summary and the last pages when the summary is current.
            summary, recent = planned_context(stored)
            if summary:
                prompt_values["summary"], story_text = summary, recent
    pages: list[dict[str, Any]] = []
    proposed: list[dict[str, Any]] = []
    changed: dict[str, Any] | None = None
    resolved_model: str | None = None
    selection = _selection(payload, stored) if action in PAGE_ACTIONS and interaction_mode != "story" else None
    if selection is not None:
        # A selection is reworked alone, between the text before it and the rest of its page (ST-6.2); a
        # selection of the whole page is reworked as that page.
        page_index, start, end = selection
        page = stored[page_index]
        blocks = list(page["blocks"])
        before = "\n\n".join(part for part in (
            tagged_text(stored[page_index - 1]["blocks"]) if page_index else "", tagged_text(blocks[:start]),
        ) if part)[-_CONTEXT_TAIL_CHARS:] or None
        _report(run, 1, 1, "Writing the selection")
        checked, resolved_model = _write_page(
            build_story_prompt(**prompt_values, source_text=before, page_text=tagged_text(blocks[start:end]),
                               passage=not (start == 0 and end == len(blocks)),
                               following_text=tagged_text(blocks[end:])[:_CONTEXT_TAIL_CHARS] or None, cast=cast),
            cast, provider_id=provider_id, model_id=model_id)
        pages = [{"chapter": other["chapter"], "title": other["title"],
                  "blocks": [*blocks[:start], *checked.blocks, *blocks[end:]] if index == page_index
                  else other["blocks"]} for index, other in enumerate(stored)]
        proposed.extend(checked.new_characters)
        changed = {"page_id": page["id"], "start": start, "end": end, "original": blocks[start:end],
                   "proposed": checked.blocks}
    elif action in PAGE_ACTIONS and stored:
        # Each page is reworked on its own, with the end of the page before it for context.
        for index, page in enumerate(stored):
            _stop_if_cancelled(run)
            _report(run, index + 1, len(stored), f"Writing page {index + 1} of {len(stored)}")
            before = tagged_text(stored[index - 1]["blocks"])[-_CONTEXT_TAIL_CHARS:] if index else None
            checked, resolved_model = _write_page(
                build_story_prompt(**prompt_values, source_text=before, page_text=tagged_text(page["blocks"]),
                                   cast=cast),
                cast, provider_id=provider_id, model_id=model_id)
            pages.append({"chapter": page["chapter"], "title": page["title"], "blocks": checked.blocks})
            proposed.extend(checked.new_characters)
            cast.extend(checked.new_characters)
    else:
        checked, resolved_model = _write_page(
            build_story_prompt(**prompt_values, source_text=story_text, cast=cast),
            cast, provider_id=provider_id, model_id=model_id)
        pages.append({"title": checked.title or "", "blocks": checked.blocks,
                      "suggested_moves": checked.suggested_moves, "summary": checked.summary})
        proposed.extend(checked.new_characters)
    is_version = action in service.VERSION_ACTIONS
    # A story the model gave no title stays untitled, so a later page is still asked for one; "Untitled story"
    # names the result only.
    title = requested_title or (None if is_version else pages[0].get("title")) or project["project"]["title"] or None
    ref = service.record_job_result(
        database, context, project_id=project_id, job_id=job_id, action=action,
        interaction_mode=interaction_mode, title=title, pages=pages,
        player_text=_text(payload.get("user_response")) if interaction_mode == "story" else None,
        chosen_suggestion=_text(payload.get("chosen_suggestion")), chapter=chapter, new_characters=proposed,
        beat_id=planned[1]["id"] if planned is not None else None,
        selection=changed,
    )
    content = service.blocks_text(changed["proposed"]) if changed is not None \
        else "\n\n".join(service.blocks_text(page["blocks"]) for page in pages)
    heading = None if is_version else pages[0].get("title")
    return _story_result(title or "Untitled story", f"# {heading}\n\n{content}" if heading else content, ref,
                         provider_id=provider_id, model_id=model_id, resolved_model=resolved_model)


#: How much of the page before a reworked page goes with it as context.
_CONTEXT_TAIL_CHARS = 1_500


def _selection(payload: dict[str, Any], stored: list[dict[str, Any]]) -> tuple[int, int, int] | None:
    """The page and block range ``[start, end)`` a job reworks (ST-6.2); a range the story lacks fails."""
    selection = payload.get("selection")
    if selection is None:
        return None
    if not isinstance(selection, dict):
        raise ValueError("story_selection_invalid")
    page_id, start, end = selection.get("page_id"), selection.get("start"), selection.get("end")
    index = next((index for index, page in enumerate(stored) if page["id"] == page_id), None)
    if index is None:
        raise ValueError("story_selection_page_not_found")
    if not all(isinstance(value, int) and not isinstance(value, bool) for value in (start, end)) \
            or not 0 <= start < end <= len(stored[index]["blocks"]):
        raise ValueError("story_selection_invalid")
    # The text the writer selected travels with the job: a page edited before the job ran is not reworked
    # at the old indices, which would now hold other text.
    texts = selection.get("texts")
    if not isinstance(texts, list) or not all(isinstance(text, str) for text in texts):
        raise ValueError("story_selection_invalid")
    # The writer selected the text as the API shows it, cleaned of control characters; an older page (imported
    # or restored from a version) may still hold some, so it is compared cleaned too.
    if texts != [CONTROL_CHARS.sub("", block.get("text") or "") for block in stored[index]["blocks"][start:end]]:
        raise ValueError("story_selection_page_changed")
    return index, start, end


def _preset_instructions(project: dict[str, Any]) -> str | None:
    """The instructions of the preset the story is written with (ST-5.2), if it has one."""
    preset_id = project["project"].get("preset_id")
    note = next((note for note in project["notes"]
                 if preset_id and note["kind"] == "preset" and note["id"] == preset_id), None)
    if note is None:
        return None
    return (note["body"] or "").strip() or None


def _planned_beat(project: dict[str, Any], payload: dict[str, Any],
                  interaction_mode: str) -> tuple[dict[str, Any], dict[str, Any]] | None:
    """The chapter and beat of the plan a writing page is drafted from; a beat the plan doesn't have fails."""
    beat_id = _text(payload.get("beat_id"))
    if beat_id is None or interaction_mode == "story":
        return None
    from . import service

    found = service.outline_beat(project["project"].get("outline") or [], beat_id)
    if found is None:
        raise ValueError("story_beat_not_found")
    return found


def _beat_text(chapter: dict[str, Any], beat: dict[str, Any]) -> str:
    heading = f"Chapter {chapter['chapter']}" + (f": {chapter['title']}" if chapter.get("title") else "")
    return f"{heading}\n{beat['text']}"


def _plan_story(job_id: str, payload: dict[str, Any], project: dict[str, Any], *, premise: str,
                title: str | None, style_notes: str | None, provider_id: str | None,
                model_id: str | None) -> dict[str, Any]:
    """Plan the story as chapters of beats and store the plan on the project, once (ST-5.1)."""
    from app.persistence.database import default_database
    from app.runtime.tenant_context import current_tenant

    from . import service

    database, context = default_database(), current_tenant()
    row = project["project"]
    given_title = title or row["title"] or None
    title = given_title or "Untitled story"
    if row.get("outline_source_job_id") == job_id:
        ref = {"project_id": row["id"], "outline_job_id": job_id}
        return {**_story_result(title, outline_text(row.get("outline") or []), ref, provider_id=provider_id,
                                model_id=model_id, resolved_model=None), "artifact_type": "story_outline"}
    count = payload.get("outline_chapters")
    count = count if isinstance(count, int) and not isinstance(count, bool) and 1 <= count <= PLANNED_CHAPTERS_MAX \
        else DEFAULT_CHAPTERS
    stored = project["pages"]
    summary, _ = interactive_context(stored)
    prompt = build_outline_prompt(
        premise=premise, chapters=count, title=given_title,
        tone=_text(payload.get("tone")), writing_style=_text(payload.get("writing_style")),
        cast=project["characters"], notes=project["notes"], style_notes=style_notes, summary=summary,
        story_text="\n\n".join(tagged_text(page["blocks"]) for page in stored) or None,
    )
    reply, resolved_model = _generate(prompt, STORY_OUTLINE_CONTRACT, STORY_OUTLINE_BUDGET, what="outline",
                                      provider_id=provider_id, model_id=model_id)
    chapters = check_outline(reply)
    if not chapters:
        raise RuntimeError("The story outline could not be written: it planned no beats")
    ref = service.record_outline(database, context, project_id=row["id"], job_id=job_id, chapters=chapters)
    return {**_story_result(title, outline_text(chapters), ref, provider_id=provider_id, model_id=model_id,
                            resolved_model=resolved_model), "artifact_type": "story_outline"}


def _generate(prompt: StoryPrompt, contract: Any, budget: Any, *, what: str, provider_id: str | None,
              model_id: str | None) -> tuple[Any, str | None]:
    """One structured reply from the model. A reply cut off at its token limit or that doesn't parse is asked
    for again within the budget; it is never saved."""
    from app.providers import ChatMessage
    from app.providers.service import provider_lease
    from app.providers.structured import StructuredOutputError, StructuredOutputGateway

    model = model_name_of(model_id) or None
    with provider_lease(_provider_key(provider_id)) as provider:
        if provider is None:
            raise RuntimeError("LLM provider is unavailable")
        gateway = StructuredOutputGateway(provider)
        try:
            reply = gateway.generate(
                [ChatMessage(role="system", content=prompt.system), ChatMessage(role="user", content=prompt.user)],
                contract=contract, model=model, retry_budget=budget,
            )
        except StructuredOutputError as exc:
            cause = getattr(exc, "last_error", None) or exc
            raise RuntimeError(f"The story {what} could not be written: {cause}") from exc
    diagnostics = gateway.last_diagnostics
    return reply, (diagnostics.model if diagnostics and diagnostics.model else model)


def _write_page(prompt: StoryPrompt, cast: list[dict[str, Any]], *, provider_id: str | None,
                model_id: str | None) -> tuple[CheckedPage, str | None]:
    """One page from the model through the structured gateway, checked against the cast (ST-2.1, ST-2.2)."""
    reply, model = _generate(prompt, STORY_PAGE_CONTRACT, STORY_PAGE_BUDGET, what="page",
                             provider_id=provider_id, model_id=model_id)
    return check_page(reply, cast), model


def _stop_if_cancelled(run: JobRun[Any] | None) -> None:
    if run is not None and run.cancelled():
        raise RuntimeError("story job was cancelled")


def _report(run: JobRun[Any] | None, current: int, total: int, message: str) -> None:
    report = _progress_reporter(run)
    if report is not None:
        report(current, total, message)


def _story_result(title: str, content: str, ref: dict[str, Any], *, provider_id: str | None, model_id: str | None,
                  resolved_model: str | None) -> dict[str, Any]:
    return {
        "artifact_type": "story",
        "title": title,
        "content": content,
        "log_message": "Story generated by local provider",
        "provider_id": provider_id,
        "model_id": model_id,
        "resolved_model": resolved_model,
        "story_ref": ref,
    }


_DEFAULT_SYSTEM_PROMPT = "You are a helpful AI assistant."


def _call_chat_provider(
    prompt: str,
    *,
    provider_id: str | None,
    model_id: str | None,
    system: str = _DEFAULT_SYSTEM_PROMPT,
) -> tuple[str, str | None]:
    from app.providers import ChatMessage
    from app.providers.service import chat_completion

    provider_name = _provider_key(provider_id)
    response = chat_completion(
        messages=[
            ChatMessage(role="system", content=system),
            ChatMessage(role="user", content=prompt),
        ],
        provider_name=provider_name,
        model=model_name_of(model_id) or None,
        stream=False,
    )
    content = (getattr(response, "content", "") or "").strip()
    if not content:
        raise RuntimeError("LLM response was empty")
    return content, getattr(response, "model", None) or model_name_of(model_id) or None


def _progress_reporter(run: JobRun[Any] | None):
    if run is None:
        return None

    def report(current: int, total: int, message: str) -> None:
        try:
            run.store.update_progress(run.job.id, JobProgress(current=current, total=total, message=message))
        except Exception:  # progress is shown to the producer; the script does not fail for it
            _LOG.debug("podcast script progress was not saved", exc_info=True)

    return report


def _provider_key(value: str | None) -> str | None:
    return provider_id_of(value) or None


def _require_text(value: object, message: str) -> str:
    text = _text(value)
    if not text:
        raise ValueError(message)
    return text


def _page_lines(value: object) -> int | None:
    """A page length in lines the prompt can ask for; anything else asks for the usual length."""
    if isinstance(value, int) and not isinstance(value, bool) and PAGE_LINES_MIN <= value <= PAGE_LINES_MAX:
        return value
    return None


def _text(value: object) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None
