"""The creation wizard's World Forge campaign plays from a world (roadmap §4.4; owner decision, 2026-10-25).

With World Forge on, the wizard makes a world of the player's library and launches the campaign from it, like any
published world, so every mechanic the turn pipeline runs plays in it. The world is made by the library's own
lifecycle, with its own gates: the world and its genre profile, the profile approved, its lore generated by the
library's jobs (signed as model output), the candidates accepted, the world published and certified, an opening
prepared, and the campaign launched from that opening under the id the wizard already gave the player. Submitting
the wizard is the player's approval of the profile and the lore (``approved_by`` says so).

``advance_wizard_world`` takes one step and says where the world stands; it reads every step's state from the
library (nothing of its own is kept), so it can be called again after a restart or a retry and goes on from there.
The genesis job calls it until the campaign is launched, deferring itself while the library's workers generate.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Callable, Mapping

WIZARD_WORLD_VERSION = "rpg_wizard_world_v2"
APPROVED_BY = "campaign-wizard"
_SAFE_ID = re.compile(r"[^A-Za-z0-9_.:-]+")
# How far along each stage is, for the wizard's progress bar.
STAGE_PERCENT = {"world": 5, "profile": 10, "generating": 20, "publishing": 80, "opening": 90, "launching": 95,
                 "launched": 100}


@dataclass(frozen=True)
class WizardWorldStep:
    stage: str  # world, profile, generating, publishing, opening, launched
    waiting: bool = False  # on the library's workers: call again later
    world_id: str = ""
    detail: dict[str, Any] = field(default_factory=dict)

    @property
    def launched(self) -> bool:
        return self.stage == "launched"

    @property
    def percent(self) -> int:
        return STAGE_PERCENT.get(self.stage, 0)


def wizard_world_id(campaign_id: str) -> str:
    """The world a wizard campaign's World Forge makes."""
    return f"world:campaign:{_SAFE_ID.sub('-', campaign_id).strip('-') or 'campaign'}"


def _world_request(contract: Any, world_id: str, campaign_id: str) -> Any:
    from app.apps.rpg.genesis.worlds.contracts import WorldProjectCreate

    template = str(contract.campaign_template or "classic_fantasy")
    hook = str(contract.story_options.opening_hook or "")
    directives = [str(line) for line in contract.world_forge.custom_directives if str(line).strip()]
    description = " ".join([*directives, *([f"It opens with {hook}."] if hook else [])]) or (
        f"A {template.replace('_', ' ')} world, made for {contract.identity.name or 'a new hero'}'s campaign.")
    return WorldProjectCreate(
        world_id=world_id, title=f"{contract.identity.name or 'A hero'}'s world"[:120], description=description,
        source_mode="ai", genre=str(contract.genre or template), tone=str(contract.tone or "heroic adventure"),
        seed=int(contract.world_options.seed or 0),
        metadata={"campaign_mode": "persistent_living_world", "campaign_template": template,
                  "wizard_world": {"version": WIZARD_WORLD_VERSION, "campaign_id": campaign_id}})


def opening_document(row: Mapping[str, Any]) -> dict[str, Any]:
    """A prepared opening's scenario revision document (the one the launch repair pinned)."""
    revision = dict(dict(row.get("result") or {}).get("scenario_revision") or {})
    return dict(revision.get("document") or revision)


def _opening(prepared: Mapping[str, Any], wanted: str) -> Mapping[str, Any] | None:
    """The prepared opening to launch: the one whose place the wizard named, else the first."""
    rows = [dict(row) for row in prepared.get("prepared") or () if isinstance(row, Mapping)]
    words = set(re.findall(r"[a-z0-9]+", wanted.casefold().replace("_", " ")))
    named = [row for row in rows if words and words <= set(re.findall(
        r"[a-z0-9]+", f"{row.get('title') or ''} {opening_document(row).get('starting_location_id') or ''}"
        .casefold().replace("-", " ")))]
    found = named or rows
    return found[0] if found else None


def advance_wizard_world(
    contract: Any,
    *,
    campaign_id: str,
    launch: Callable[[Mapping[str, Any]], dict[str, Any]],
    database: Any | None = None,
) -> WizardWorldStep:
    """One step of making the campaign's world and launching it. ``launch(opening)`` launches the campaign from a
    prepared opening and returns the launch result."""
    from app.persistence.unit_of_work import unit_of_work
    from app.security.tenant_context import current_tenant
    from app.apps.rpg.genesis.worlds.generation_acceptance import accept_world_generation_candidates
    from app.apps.rpg.genesis.worlds.launch_repair_service import prepare_opening_scenarios_for_launch
    from app.apps.rpg.genesis.worlds.library_service import (
        publish_world_library_generation,
        read_world_generation,
        start_world_library_generation,
    )
    from app.apps.rpg.genesis.worlds.postgres_service import create_world_project
    from app.apps.rpg.genesis.worlds.profile_authoring import approve_world_profile_review, read_world_profile_review

    world_id = wizard_world_id(campaign_id)
    context = current_tenant()
    with unit_of_work(database) as work:
        world = work.world_scenarios.get_world(context, world_id)
        runs = work.world_library.list_generation_runs(context, world_id=world_id, limit=1) if world else []
        work.rollback()
    if world is None:
        create_world_project(_world_request(contract, world_id, campaign_id), database=database)
        return WizardWorldStep("world", waiting=True, world_id=world_id)

    review = read_world_profile_review(world_id, database=database)["review"]
    if review["status"] != "approved":
        if not review.get("profile"):  # its genre profile is still being made
            return WizardWorldStep("profile", waiting=True, world_id=world_id)
        approve_world_profile_review(world_id, expected_profile_revision=int(review["profile_revision"]),
                                     approved_by=APPROVED_BY, database=database)
        return WizardWorldStep("profile", world_id=world_id)

    if not runs:
        start_world_library_generation(world_id, depth=str(contract.world_forge.depth or "standard"),
                                       starting_location=str(contract.world_options.starting_location or ""),
                                       database=database)
        return WizardWorldStep("generating", waiting=True, world_id=world_id)
    run = runs[0]
    status = str(run.get("status") or "")
    if status in {"planned", "running"}:
        state = read_world_generation(str(run["run_id"]), database=database)  # reconciles, and wakes its worker
        status = str(state["run"].get("status") or "")
        if status in {"planned", "running"}:
            return WizardWorldStep("generating", waiting=True, world_id=world_id,
                                   detail={"progress": dict(state["run"].get("progress") or {})})
    if status == "failed":
        raise ValueError(f"wizard_world_generation_failed:{run.get('run_id')}")
    if status == "review":
        state = read_world_generation(str(run["run_id"]), database=database, reconcile=False)
        pending = [str(row.get("topic_id")) for row in state["topic_results"] if str(row.get("status")) != "accepted"]
        if pending:
            accept_world_generation_candidates(str(run["run_id"]), topic_ids=pending, database=database)
        publish_world_library_generation(str(run["run_id"]), database=database)
        return WizardWorldStep("publishing", world_id=world_id)

    prepared = prepare_opening_scenarios_for_launch(world_id, database=database)  # idempotent: the openings
    opening = _opening(prepared, str(contract.world_options.starting_location or ""))
    if opening is None:
        raise ValueError(f"wizard_world_opening_unavailable:{prepared.get('status')}")
    return WizardWorldStep("launched", world_id=world_id, detail={"launch": launch(opening)})


__all__ = ["APPROVED_BY", "STAGE_PERCENT", "WIZARD_WORLD_VERSION", "WizardWorldStep", "advance_wizard_world",
           "opening_document", "wizard_world_id"]
