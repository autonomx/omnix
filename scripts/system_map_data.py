def node(id, label, layer, summary, paths, *, feature=None, port=None, key_files=(), invariants=(), tests=(), docs=()):
    n = {"id": id, "label": label, "layer": layer, "summary": summary, "paths": list(paths)}
    if feature:
        n["feature_id"] = feature
    if port:
        n["port"] = port
    if key_files:
        n["key_files"] = list(key_files)
    if invariants:
        n["invariants"] = list(invariants)
    if tests:
        n["tests"] = list(tests)
    if docs:
        n["docs"] = list(docs)
    return n


